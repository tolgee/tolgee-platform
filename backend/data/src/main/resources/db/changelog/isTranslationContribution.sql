CREATE OR REPLACE FUNCTION is_translation_contribution(activity_type text)
    RETURNS BOOLEAN AS
$$
SELECT coalesce(activity_type IN (
    'SET_TRANSLATIONS', 'SET_TRANSLATION_STATE', 'COMPLEX_EDIT',
    'TRANSLATION_COMMENT_ADD', 'TRANSLATION_COMMENT_EDIT', 'TRANSLATION_COMMENT_DELETE', 'TRANSLATION_COMMENT_SET_STATE',
    'CREATE_SUGGESTION', 'ACCEPT_SUGGESTION', 'DECLINE_SUGGESTION', 'REVERSE_SUGGESTION', 'DELETE_SUGGESTION',
    'SUGGESTION_SET_ACTIVE'
    ), false)
$$ LANGUAGE sql IMMUTABLE;
